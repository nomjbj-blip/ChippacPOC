/* Added for double DEV */
#define D(x)    (double) atof(callinfo->parms[(x)])
#define	F(x)	atof(callinfo->parms[(x)]) 
#define	S(x)	callinfo->parms[(x)] 
#define	C(x)	callinfo->parms[(x)][0]

#endif /*!_MSDOS*/

