/* PARM_ERR() always returns 0 (for later cast to int, long, float, or char *)
 * the last expression in a comma-separated list of expressions is the
 * value of the entire list.
 */

#define PARM_ERR(x) (outputf("Error: missing parameter #%d\n", (x)), 0)

/* macros to do some error checking on the parms[x] string,
 * and provide a short way to write atoi(parms[x]) etc.
 * this scheme takes a lot of code space, but it's practically bulletproof
 *
 * If there is an error (a null string is passed in),
 * these macros return 0 cast to the proper type and print an error
 * message.
 */
#define I(x)    (callinfo->parms[(x)] != NULL ? atoi(callinfo->parms[(x)]) : (int)PARM_ERR(x))

#ifdef L
#undef L
#endif
#define L(x)    (callinfo->parms[(x)] != NULL ? atol(callinfo->parms[(x)]) : (long)PARM_ERR(x))

#define F(x)    (callinfo->parms[(x)] != NULL ? (float) atof(callinfo->parms[(x)]) : (float)PARM_ERR(x))

#define D(x)    (callinfo->parms[(x)] != NULL ? (double) atof(callinfo->parms[(x)]) : (double)PARM_ERR(x))

#define S(x)    (callinfo->parms[(x)] != NULL ? callinfo->parms[(x)] : (char *)PARM_ERR(x))

#ifdef C
#undef C
#endif
#define C(x)    (callinfo->parms[(x)] != NULL ? callinfo->parms[(x)][0] : (char)PARM_ERR(x))

#else /*!_MSDOS*/

#ifdef WIN32
#ifdef L
#undef L
#endif
#ifdef C
#undef C
#endif
#endif

