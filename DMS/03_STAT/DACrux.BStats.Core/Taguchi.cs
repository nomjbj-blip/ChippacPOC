        private static DataTable GetDesignList(int Level, int FCount)
        {
            string strColumn = string.Empty;
            if (m_dtDesignList == null) MakeDesignList();
            try
            {
                if (Level == 0)
                {
                    // 혼합수준
                    strColumn = "LEVELM";
                }
                else if (Level == 2 || Level == 3 || Level == 4 || Level == 5)
                {
                    // 2,3,4,5
                    strColumn = string.Format("LEVEL{0}", Level);
                }

                DataView dv = new DataView(m_dtDesignList);
                dv.RowFilter = string.Format("{0} >= {1}", strColumn, FCount);

                DataTable dtResult = new DataTable();
                dtResult.Columns.Add("RUN", typeof(string));
                dtResult.Columns.Add(string.Format("{0} ** 열", Level), typeof(string));

                for (int i = 0; i < dv.Count; i++)
                {
                    dtResult.Rows.Add(new object[] { dv[i]["DESIGN"].ToString(), string.Format("{0} ** {1}", Level, dv[i][strColumn].ToString()) });
                }

                return dtResult;

            }
            catch (Exception ex)
            {
                throw ex;
            }
        }

