-- 유지 기준 (아래 값 중 하나라도 MAPID 와 같으면 유지, 나머지 Map 은 삭제):
--   1) TQP_LOT.DEVICE_ALIAS  - TQP_WAFER 행이 있는 Lot 만 (TQP_WAFER.xml: A.DEVICE_ALIAS = C.MAPID)
--   2) TQP_MAPCFG.DEVICE_ALIAS - TQP_WAFER.MAP_CFG_SEQ 가 가리키는 설정만
--   3) TQP_WAFER_SUM.DEVICE_ALIAS / PRODUCT (TQD_DEFECT_DIE.xml: T1.DEVICE_ALIAS = T2.MAPID)
--   4) TQD_INSP_INFO.PRODUCT (DMS 검사 Wafer, TQD_INSP_INFO.xml: A.PRODUCT = B.MAPID)
--   5) 위 값이 TQP_PRODUCT.PRODUCT 이면 그 TQP_PRODUCT.MAPID 도 유지 (GET_MAPDEF_BY_LOTID 경로)
--   Lot / 요약만 있는 테이블(TQP_LOT 단독 / TQP_LOT_SUM / TQD_LOT / TQD_PRODUCT / TQC_*)은 사용으로 보지 않는다.
--
-- 영향:
--   - TQP_PRODUCT 행은 지우지 않는다. 삭제된 MAPID 를 가리키는 TQP_PRODUCT 행이 남는다 (조회 쿼리는 MAPDEF 와 조인/외부조인이라 Map 없음으로 보임).
--   - FK 없음. TQP_ZONE.MAPID 해당 0행. MESMGR.MQBM* 는 대상 아님.
--   - Map Setup 화면으로 새로 만든 Map 도 Wafer 데이터가 없으면 삭제된다. 다른 DB 에 적용할 때는 아래 미리보기 목록을 먼저 확인한다.
--   - MAPID 만 비교한다 (FACTORY 무시, 2026-10-13 로컬 DB 는 FAB2 하나).
-- 적용: 2026-10-13 로컬 docker oracle19c DMSMGR.

