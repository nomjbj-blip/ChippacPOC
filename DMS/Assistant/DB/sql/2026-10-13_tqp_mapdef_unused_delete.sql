PROMPT ===== 미리보기: 유지할 Map =====
SELECT M.MAPID
  FROM TQP_MAPDEF M
 WHERE M.MAPID IN (SELECT V FROM (
           SELECT L.DEVICE_ALIAS V FROM TQP_LOT L WHERE EXISTS (SELECT 1 FROM TQP_WAFER W WHERE W.LOT_SEQ = L.LOT_SEQ)
           UNION SELECT C.DEVICE_ALIAS FROM TQP_MAPCFG C WHERE EXISTS (SELECT 1 FROM TQP_WAFER W WHERE W.MAP_CFG_SEQ = C.MAP_CFG_SEQ)
           UNION SELECT DEVICE_ALIAS FROM TQP_WAFER_SUM
           UNION SELECT PRODUCT FROM TQP_WAFER_SUM
           UNION SELECT PRODUCT FROM TQD_INSP_INFO) K
       UNION
       SELECT P.MAPID FROM TQP_PRODUCT P WHERE P.PRODUCT IN (
           SELECT L.DEVICE_ALIAS FROM TQP_LOT L WHERE EXISTS (SELECT 1 FROM TQP_WAFER W WHERE W.LOT_SEQ = L.LOT_SEQ)
           UNION SELECT C.DEVICE_ALIAS FROM TQP_MAPCFG C WHERE EXISTS (SELECT 1 FROM TQP_WAFER W WHERE W.MAP_CFG_SEQ = C.MAP_CFG_SEQ)
           UNION SELECT DEVICE_ALIAS FROM TQP_WAFER_SUM
           UNION SELECT PRODUCT FROM TQP_WAFER_SUM
           UNION SELECT PRODUCT FROM TQD_INSP_INFO))
 ORDER BY M.MAPID;

