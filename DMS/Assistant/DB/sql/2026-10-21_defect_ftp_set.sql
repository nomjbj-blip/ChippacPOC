-- DEFECT_FTP(Defect 이미지를 받는 FTP) 설정 값을 바꾼다. (2026-10-21)
-- 대상: 스키마가 이미 만들어진 DB 의 TQC_CONFIG (예: 고객 DB TRAINING). 대상 사용자로 실행한다.
-- 같은 CATEGORY / NAME 행이 있으면 VALUE 를 바꾸고, 없으면 새로 넣는다. 여러 번 실행해도 된다.
-- 암호는 실행할 때 묻는다(화면에 보이지 않음). 파일에 암호를 적지 않는다.
-- 화면은 ftp://IP:PORT + MAIN_PATH + DB 이미지 경로(TQD_IMAGES.IMAGE_PATH) 로 이미지를 받는다.
-- 실행: sqlplus <사용자>@<DB> @2026-10-21_defect_ftp_set.sql   (기록: defect_ftp_set.log)

SET DEFINE ON
SET VERIFY OFF
SET FEEDBACK ON
WHENEVER SQLERROR EXIT ROLLBACK

DEFINE FTP_IP = 10.86.253.162
DEFINE FTP_PORT = 21
DEFINE FTP_ID = POC
DEFINE FTP_MAIN_PATH = '/DMS_IMAGE'
ACCEPT FTP_PASS CHAR PROMPT 'DEFECT_FTP password: ' HIDE

SPOOL defect_ftp_set.log

PROMPT == 바꾸기 전 (PASS 는 표시하지 않음)
SELECT CATEGORY, NAME, CASE WHEN NAME = 'PASS' THEN '(hidden)' ELSE VALUE END AS VALUE
  FROM TQC_CONFIG
 WHERE CATEGORY = 'DEFECT_FTP'
 ORDER BY NAME;

MERGE INTO TQC_CONFIG T
USING (
    SELECT 'DEFECT_FTP' AS CATEGORY, 'IP' AS NAME, '&FTP_IP' AS VALUE FROM DUAL
    UNION ALL SELECT 'DEFECT_FTP', 'PORT', '&FTP_PORT' FROM DUAL
    UNION ALL SELECT 'DEFECT_FTP', 'ID', '&FTP_ID' FROM DUAL
    UNION ALL SELECT 'DEFECT_FTP', 'PASS', '&FTP_PASS' FROM DUAL
    UNION ALL SELECT 'DEFECT_FTP', 'MAIN_PATH', '&FTP_MAIN_PATH' FROM DUAL
) S
ON (T.CATEGORY = S.CATEGORY AND T.NAME = S.NAME)
WHEN MATCHED THEN
    UPDATE SET T.VALUE = S.VALUE
WHEN NOT MATCHED THEN
    INSERT (CATEGORY, NAME, VALUE, TYPE, "COMMENT")
    VALUES (S.CATEGORY, S.NAME, S.VALUE, 'STRING', '@COMMENT@');

COMMIT;

