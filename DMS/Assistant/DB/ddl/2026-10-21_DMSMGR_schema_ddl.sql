  CREATE OR REPLACE FUNCTION "DBH_DATE" (
    p_date   IN DATE,
    p_format IN VARCHAR2
) RETURN VARCHAR2
AUTHID DEFINER
IS
    v_format VARCHAR2(8) := UPPER(TRIM(p_format));
BEGIN
    -- ������ ��������� ��������� ������ ��������� ������ ������ ��������� NULL��� ������������.
    IF p_date IS NULL THEN
        RETURN NULL;
    END IF;

    -- TQC_MATCH_SUM��� YEAR, MONTH, DAY, WEEK, TRAN_DAY ��������� ��������� ��������� ������������.
    CASE v_format
        WHEN 'YYYY' THEN RETURN TO_CHAR(p_date, 'YYYY');
        WHEN 'MM' THEN RETURN TO_CHAR(p_date, 'MM');
        WHEN 'DD' THEN RETURN TO_CHAR(p_date, 'DD');
        WHEN 'WW' THEN RETURN TO_CHAR(p_date, 'WW');
        WHEN 'YYYYMMDD' THEN RETURN TO_CHAR(p_date, 'YYYYMMDD');
        ELSE
            RAISE_APPLICATION_ERROR(-20002, 'Unsupported DBH_DATE format: ' || NVL(p_format, 'NULL'));
    END CASE;
END;
