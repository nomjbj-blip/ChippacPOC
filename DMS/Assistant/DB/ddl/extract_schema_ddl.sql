-- PROMPT 는 줄 끝 ';' 하나를 지우므로 ';;' 로 써야 결과 파일에 ';' 가 남는다.
PROMPT SELECT OBJECT_TYPE, COUNT(*) CNT, SUM(DECODE(STATUS, 'VALID', 0, 1)) INVALID_CNT FROM USER_OBJECTS WHERE OBJECT_NAME NOT LIKE 'BIN$%' GROUP BY OBJECT_TYPE ORDER BY 1;;
PROMPT SELECT CONSTRAINT_TYPE, COUNT(*) CNT FROM USER_CONSTRAINTS WHERE TABLE_NAME NOT LIKE 'BIN$%' GROUP BY CONSTRAINT_TYPE ORDER BY 1;;

