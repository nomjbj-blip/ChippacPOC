PROMPT -- ==== 1. SEQUENCE ====
SELECT REPLACE(REPLACE(REPLACE(
           REGEXP_REPLACE(DBMS_METADATA.GET_DDL('SEQUENCE', S.SEQUENCE_NAME, S.SEQUENCE_OWNER),
                          'START WITH [0-9]+',
                          'START WITH ' || TO_CHAR(CASE WHEN S.INCREMENT_BY < 0 THEN S.MAX_VALUE ELSE S.MIN_VALUE END, 'TM9')),
           ' NOKEEP ', ' '), ' NOSCALE ', ' '), ' GLOBAL ;', ' ;')
  FROM DBA_SEQUENCES S
 WHERE S.SEQUENCE_OWNER = UPPER('&OWNER')
 ORDER BY S.SEQUENCE_NAME;

PROMPT
PROMPT -- ==== 2. TABLE (PK / UK / CHECK 포함, FK 는 5번) ====
SELECT REGEXP_REPLACE(DBMS_METADATA.GET_DDL('TABLE', T.TABLE_NAME, T.OWNER), 'CONSTRAINT "SYS_C[0-9]+" ', '')
  FROM DBA_TABLES T
 WHERE T.OWNER = UPPER('&OWNER') AND T.DROPPED = 'NO' AND T.NESTED = 'NO' AND T.SECONDARY = 'N' AND T.IOT_NAME IS NULL
   AND NOT REGEXP_LIKE(T.TABLE_NAME, '&EXCL')
   AND NOT EXISTS (SELECT 1 FROM DBA_MVIEWS M WHERE M.OWNER = T.OWNER AND M.MVIEW_NAME = T.TABLE_NAME)
 ORDER BY T.TABLE_NAME;

PROMPT
PROMPT -- ==== 3. COMMENT ====
SELECT DBMS_METADATA.GET_DEPENDENT_DDL('COMMENT', T.TABLE_NAME, T.OWNER)
  FROM DBA_TABLES T
 WHERE T.OWNER = UPPER('&OWNER') AND T.DROPPED = 'NO' AND T.NESTED = 'NO' AND T.SECONDARY = 'N' AND T.IOT_NAME IS NULL
   AND NOT REGEXP_LIKE(T.TABLE_NAME, '&EXCL')
   AND (EXISTS (SELECT 1 FROM DBA_TAB_COMMENTS C WHERE C.OWNER = T.OWNER AND C.TABLE_NAME = T.TABLE_NAME AND C.COMMENTS IS NOT NULL)
        OR EXISTS (SELECT 1 FROM DBA_COL_COMMENTS C WHERE C.OWNER = T.OWNER AND C.TABLE_NAME = T.TABLE_NAME AND C.COMMENTS IS NOT NULL))
 ORDER BY T.TABLE_NAME;

PROMPT
PROMPT -- ==== 4. INDEX (PK / UK 제약용 인덱스 제외) ====
SELECT DBMS_METADATA.GET_DDL('INDEX', I.INDEX_NAME, I.OWNER)
  FROM DBA_INDEXES I
  JOIN DBA_TABLES T ON T.OWNER = I.TABLE_OWNER AND T.TABLE_NAME = I.TABLE_NAME AND T.DROPPED = 'NO'
 WHERE I.OWNER = UPPER('&OWNER') AND I.INDEX_TYPE NOT IN ('LOB', 'IOT - TOP')
   AND NOT REGEXP_LIKE(I.TABLE_NAME, '&EXCL')
   AND NOT EXISTS (SELECT 1 FROM DBA_CONSTRAINTS C
                    WHERE C.OWNER = I.TABLE_OWNER AND C.INDEX_NAME = I.INDEX_NAME AND C.CONSTRAINT_TYPE IN ('P', 'U'))
 ORDER BY I.TABLE_NAME, I.INDEX_NAME;

PROMPT
PROMPT -- ==== 5. FOREIGN KEY ====
SELECT REGEXP_REPLACE(DBMS_METADATA.GET_DDL('REF_CONSTRAINT', C.CONSTRAINT_NAME, C.OWNER), 'CONSTRAINT "SYS_C[0-9]+" ', '')
  FROM DBA_CONSTRAINTS C
  JOIN DBA_TABLES T ON T.OWNER = C.OWNER AND T.TABLE_NAME = C.TABLE_NAME AND T.DROPPED = 'NO'
  JOIN DBA_CONSTRAINTS R ON R.OWNER = C.R_OWNER AND R.CONSTRAINT_NAME = C.R_CONSTRAINT_NAME
 WHERE C.OWNER = UPPER('&OWNER') AND C.CONSTRAINT_TYPE = 'R'
   AND NOT REGEXP_LIKE(C.TABLE_NAME, '&EXCL')
   AND NOT REGEXP_LIKE(R.TABLE_NAME, '&EXCL')
 ORDER BY C.TABLE_NAME, C.CONSTRAINT_NAME;

PROMPT
PROMPT -- ==== 6. VIEW / FUNCTION / PROCEDURE / PACKAGE / TRIGGER ====
SELECT REGEXP_REPLACE(DBMS_METADATA.GET_DDL(DECODE(O.OBJECT_TYPE, 'PACKAGE', 'PACKAGE_SPEC', 'PACKAGE BODY', 'PACKAGE_BODY',
                                                   'TYPE', 'TYPE_SPEC', 'TYPE BODY', 'TYPE_BODY', O.OBJECT_TYPE),
                                            O.OBJECT_NAME, O.OWNER),
                      'CREATE OR REPLACE (NON)?EDITIONABLE ', 'CREATE OR REPLACE ', 1, 1)
  FROM DBA_OBJECTS O
 WHERE O.OWNER = UPPER('&OWNER') AND O.OBJECT_NAME NOT LIKE 'BIN$%'
   AND O.OBJECT_TYPE IN ('VIEW', 'FUNCTION', 'PROCEDURE', 'PACKAGE', 'PACKAGE BODY', 'TYPE', 'TYPE BODY', 'SYNONYM', 'TRIGGER')
 ORDER BY DECODE(O.OBJECT_TYPE, 'TYPE', 1, 'VIEW', 2, 'FUNCTION', 3, 'PROCEDURE', 4, 'PACKAGE', 5,
                 'TYPE BODY', 6, 'PACKAGE BODY', 7, 'SYNONYM', 8, 'TRIGGER', 9, 10), O.OBJECT_NAME;

PROMPT
PROMPT -- ==== 7. 확인 (결과를 위 '원본 개수' 와 비교, INVALID_CNT 는 0 이어야 한다) ====
PROMPT SPOOL OFF
