-- 스키마 DDL 추출 (2026-10-21, 읽기 전용, 데이터 제외)
-- 대상: 인자로 받은 스키마(기본 DMSMGR)의 시퀀스 / 테이블(PK / UK / CHECK 포함) / 주석 / 인덱스 / FK / 뷰 / 함수 / 프로시저 / 패키지 / 트리거
-- 제외: 데이터, 휴지통(BIN$), 아래 EXCL 에 맞는 테이블(백업 BAK* / *_BAK*, 도구 작업 테이블 TOAD_PLAN_TABLE / PLAN_TABLE)과 그 인덱스 / FK / 주석,
--       PK / UK 가 쓰는 인덱스(제약을 만들 때 같이 생긴다)
-- 출력 형식: 스키마 이름 / 테이블스페이스 / 저장 옵션을 빼서, 대상 DB 에서 접속한 사용자의 기본 테이블스페이스에 만들어지게 한다.
--   시퀀스는 데이터를 옮기지 않으므로 START WITH 를 처음 값(MINVALUE, 감소 시퀀스는 MAXVALUE)으로 되돌린다.
--   FK 는 모든 테이블을 만든 뒤 ALTER TABLE 로 붙여 테이블 생성 순서와 상관없게 한다.
--   자동 생성 이름(SYS_C...) 제약은 이름을 빼서 대상 DB 가 새 이름을 붙이게 한다(대상 DB 의 기존 이름과 겹치지 않게).
--   기본값과 같은 NOKEEP / NOSCALE / GLOBAL(시퀀스), EDITIONABLE(PL/SQL) 은 빼서 대상 DB 버전 차이로 실패하지 않게 한다.
-- 결과: 컨테이너 /tmp/schemaddl/schema_ddl.sql (UTF-8)
-- 실행: Export-SchemaDdl.ps1 이 부른다. 직접 실행할 때는 주석의 한글이 깨지지 않게 NLS_LANG 을 UTF-8 로 지정한다.
--   docker exec -e NLS_LANG=AMERICAN_AMERICA.AL32UTF8 oracle19c-DMS bash -lc 'sqlplus -s / as sysdba @/tmp/schemaddl/extract_schema_ddl.sql DMSMGR'

