-- 대상 DB 사용자에 스키마 생성 권한 주기 (2026-10-21)
-- 대상: 스키마 DDL(<날짜>_DMSMGR_schema_ddl.sql)을 실행할 사용자. 사용자는 이미 있고 접속만 되는 상태를 전제로 한다(사용자를 만들지 않는다).
-- 실행 계정: GRANT / ALTER USER 권한이 있는 계정(DBA 등). 사용자 이름이 DMSMGR 이 아니면 아래 DEFINE 을 바꾼다.
-- 권한: 스키마 DDL 에 필요한 권한만 준다 - CREATE SESSION / TABLE / SEQUENCE / PROCEDURE / VIEW / TRIGGER + 기본 테이블스페이스 QUOTA UNLIMITED
--   로컬 기준 DB 의 DMSMGR 은 RESOURCE 역할 + UNLIMITED TABLESPACE 를 쓴다. 똑같이 맞추려면 2 / 3 단계 대신 맨 아래 주석의 두 줄을 쓴다.
-- 실행: sqlplus <DBA 계정>@<대상 DB> @grant_target_user.sql

SET VERIFY OFF
DEFINE TARGET_USER = DMSMGR
WHENEVER SQLERROR EXIT SQL.SQLCODE

PROMPT 1. 사용자 / 기본 테이블스페이스
SELECT USERNAME, ACCOUNT_STATUS, DEFAULT_TABLESPACE FROM DBA_USERS WHERE USERNAME = UPPER('&TARGET_USER');

PROMPT 2. 객체 생성 권한
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE PROCEDURE, CREATE VIEW, CREATE TRIGGER TO &TARGET_USER;

PROMPT 3. 기본 테이블스페이스 QUOTA
DECLARE
    v_ts DBA_USERS.DEFAULT_TABLESPACE%TYPE;
BEGIN
    SELECT DEFAULT_TABLESPACE INTO v_ts FROM DBA_USERS WHERE USERNAME = UPPER('&TARGET_USER');
    EXECUTE IMMEDIATE 'ALTER USER "' || UPPER('&TARGET_USER') || '" QUOTA UNLIMITED ON "' || v_ts || '"';
END;
/

PROMPT 4. 확인
WHENEVER SQLERROR CONTINUE
SELECT PRIVILEGE FROM DBA_SYS_PRIVS WHERE GRANTEE = UPPER('&TARGET_USER') ORDER BY 1;
SELECT TABLESPACE_NAME, MAX_BYTES FROM DBA_TS_QUOTAS WHERE USERNAME = UPPER('&TARGET_USER');

