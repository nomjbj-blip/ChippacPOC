-- 테이블 명세서용 DB 메타데이터 추출 (2026-10-15, 읽기 전용)
-- 대상: DMSMGR 의 모든 테이블(휴지통 BIN$ 제외) - 테이블 / 컬럼 주석, 컬럼, 제약, 인덱스, 기본값, 시퀀스, E-Test 등록 Parameter
--   (명세서별 대상 테이블은 build_table_spec.py(POC GDS) / build_area_spec.py(Common / DMS / YMS) 가 고른다)
-- 결과: 컨테이너 /tmp/tablespec/ 에 tbl.csv / col.csv / cons.csv / idx.csv / def.txt / seq.csv / et_item.csv ('|' 구분, UTF-8)
-- 실행: Make-TableSpec.ps1 이 부른다. 직접 실행할 때는 한글이 깨지지 않게 NLS_LANG 을 UTF-8 로 지정한다.
--   docker exec -e NLS_LANG=AMERICAN_AMERICA.AL32UTF8 oracle19c-DMS bash -lc 'mkdir -p /tmp/tablespec; sqlplus -s / as sysdba @/tmp/tablespec/extract_table_meta.sql'
-- DATA_DEFAULT 는 LONG 형식이라 CSV 출력에서 따옴표가 깨지므로 PL/SQL 로 문자열로 바꿔 def.txt 에 따로 쓴다.

WHENEVER SQLERROR EXIT SQL.SQLCODE
SET MARKUP CSV ON DELIMITER | QUOTE ON
SET PAGESIZE 0 FEEDBACK OFF HEADING ON LINESIZE 32767 TRIMSPOOL ON

SPOOL /tmp/tablespec/tbl.csv
SELECT T.TABLE_NAME, C.COMMENTS
  FROM DBA_TABLES T
  LEFT JOIN DBA_TAB_COMMENTS C ON C.OWNER = T.OWNER AND C.TABLE_NAME = T.TABLE_NAME
 WHERE T.OWNER = 'DMSMGR' AND T.TABLE_NAME NOT LIKE 'BIN$%'
 ORDER BY 1;
SPOOL OFF

SPOOL /tmp/tablespec/col.csv
SELECT C.TABLE_NAME, C.COLUMN_ID, C.COLUMN_NAME, C.DATA_TYPE, C.DATA_LENGTH, C.CHAR_LENGTH, C.CHAR_USED,
       C.DATA_PRECISION, C.DATA_SCALE, C.NULLABLE, M.COMMENTS
  FROM DBA_TAB_COLUMNS C
  LEFT JOIN DBA_COL_COMMENTS M ON M.OWNER = C.OWNER AND M.TABLE_NAME = C.TABLE_NAME AND M.COLUMN_NAME = C.COLUMN_NAME
 WHERE C.OWNER = 'DMSMGR' AND C.TABLE_NAME NOT LIKE 'BIN$%'
 ORDER BY C.TABLE_NAME, C.COLUMN_ID;
SPOOL OFF

SPOOL /tmp/tablespec/cons.csv
SELECT K.TABLE_NAME, K.CONSTRAINT_NAME, K.CONSTRAINT_TYPE, K.SEARCH_CONDITION_VC, K.R_CONSTRAINT_NAME,
       (SELECT R.TABLE_NAME FROM DBA_CONSTRAINTS R WHERE R.OWNER = K.OWNER AND R.CONSTRAINT_NAME = K.R_CONSTRAINT_NAME) R_TABLE,
       K.DELETE_RULE, K.STATUS, K.GENERATED,
       (SELECT LISTAGG(CC.COLUMN_NAME, ', ') WITHIN GROUP (ORDER BY CC.POSITION)
          FROM DBA_CONS_COLUMNS CC WHERE CC.OWNER = K.OWNER AND CC.CONSTRAINT_NAME = K.CONSTRAINT_NAME) COLS
  FROM DBA_CONSTRAINTS K
 WHERE K.OWNER = 'DMSMGR' AND K.TABLE_NAME NOT LIKE 'BIN$%'
 ORDER BY K.TABLE_NAME, DECODE(K.CONSTRAINT_TYPE, 'P', 1, 'U', 2, 'R', 3, 'C', 4, 5), K.CONSTRAINT_NAME;
SPOOL OFF

SPOOL /tmp/tablespec/idx.csv
SELECT I.TABLE_NAME, I.INDEX_NAME, I.UNIQUENESS, I.INDEX_TYPE,
       (SELECT LISTAGG(IC.COLUMN_NAME || DECODE(IC.DESCEND, 'DESC', ' DESC', ''), ', ') WITHIN GROUP (ORDER BY IC.COLUMN_POSITION)
          FROM DBA_IND_COLUMNS IC WHERE IC.INDEX_OWNER = I.OWNER AND IC.INDEX_NAME = I.INDEX_NAME) COLS,
       (SELECT LISTAGG(CON.CONSTRAINT_TYPE, ',') WITHIN GROUP (ORDER BY CON.CONSTRAINT_TYPE)
          FROM DBA_CONSTRAINTS CON WHERE CON.OWNER = I.OWNER AND CON.INDEX_NAME = I.INDEX_NAME) USED_BY
  FROM DBA_INDEXES I
 WHERE I.OWNER = 'DMSMGR' AND I.TABLE_NAME NOT LIKE 'BIN$%'
 ORDER BY I.TABLE_NAME, I.INDEX_NAME;
SPOOL OFF

SPOOL /tmp/tablespec/seq.csv
SELECT SEQUENCE_NAME, MIN_VALUE, INCREMENT_BY, CACHE_SIZE, LAST_NUMBER
  FROM DBA_SEQUENCES
 WHERE SEQUENCE_OWNER = 'DMSMGR'
 ORDER BY 1;
SPOOL OFF

-- E-Test 등록 Parameter: YMS 데이터 테이블 TD_<Device>_<공정> 의 Parameter 컬럼 설명에 쓴다
SPOOL /tmp/tablespec/et_item.csv
SELECT DEVICE_ID, TEST_PROGRAM, ITEM_NAME, HEADER_TEXT, UNIT
  FROM DMSMGR.TQP_GDS_ET_ITEM
 ORDER BY DEVICE_ID, TEST_PROGRAM, ITEM_NAME;
SPOOL OFF

SET MARKUP CSV OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
SPOOL /tmp/tablespec/def.txt
DECLARE
    V VARCHAR2(4000);
BEGIN
    FOR R IN (SELECT TABLE_NAME, COLUMN_NAME, DATA_DEFAULT FROM DBA_TAB_COLUMNS
               WHERE OWNER = 'DMSMGR' AND TABLE_NAME NOT LIKE 'BIN$%' AND DATA_DEFAULT IS NOT NULL) LOOP
        V := R.DATA_DEFAULT;
        DBMS_OUTPUT.PUT_LINE(R.TABLE_NAME || '|' || R.COLUMN_NAME || '|' || REPLACE(REPLACE(TRIM(V), CHR(10), ' '), CHR(13), ''));
    END LOOP;
END;
/
SPOOL OFF

EXIT
