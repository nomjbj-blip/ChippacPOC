-- GDS 원본 행 테이블 TQP_GDS_SOURCE_EL 제거 (2026-10-12)
-- 원본 행은 저장할 때만 쓰고 조회하는 화면 / 서비스가 없어 제거한다. 지도 / Chain / Label 검색은 TQP_GDS_PLACED_EL만 사용한다.
-- PLACED의 SOURCE_ELEMENT_ID 컬럼은 같은 원본에서 나온 도형을 묶는 값으로 남긴다(FK / 인덱스만 제거).
-- 함께 정리: 저장 작업의 원본 건수 컬럼, Map 헤더의 원본 Payload 버전 컬럼, STREAM_KIND의 'SOURCE'.
-- 순서: FK / 인덱스 -> 테이블 -> 제약 다시 생성 -> 컬럼 삭제. 다시 실행하지 않는다(이미 지운 객체가 없으면 오류로 멈춘다).

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET ECHO OFF FEEDBACK ON

-- 1) PLACED -> SOURCE 참조 제거
ALTER TABLE DMSMGR.TQP_GDS_PLACED_EL DROP CONSTRAINT FK_GDS_PLACED_SOURCE;
DROP INDEX DMSMGR.IX_GDS_PLACED_SOURCE;

-- 2) 원본 행 테이블 삭제
DROP TABLE DMSMGR.TQP_GDS_SOURCE_EL PURGE;

-- 3) 저장 작업: 원본 건수 컬럼 제거 (건수 CHECK 를 먼저 다시 만든다)
ALTER TABLE DMSMGR.TQP_GDS_IMPORT_JOB DROP CONSTRAINT CK_GDS_IMPORT_COUNTS;
ALTER TABLE DMSMGR.TQP_GDS_IMPORT_JOB DROP (EXPECTED_SOURCE_COUNT, RECEIVED_SOURCE_COUNT);
ALTER TABLE DMSMGR.TQP_GDS_IMPORT_JOB ADD CONSTRAINT CK_GDS_IMPORT_COUNTS CHECK (
    EXPECTED_PLACED_COUNT >= 0 AND EXPECTED_POINT_COUNT >= 0 AND RECEIVED_PLACED_COUNT >= 0 AND RECEIVED_POINT_COUNT >= 0);

-- 4) 배치 기록: STREAM_KIND 에서 SOURCE 제거 (기존 SOURCE 행이 있으면 먼저 지운다)
DELETE FROM DMSMGR.TQP_GDS_IMPORT_BATCH WHERE STREAM_KIND = 'SOURCE';
COMMIT;
ALTER TABLE DMSMGR.TQP_GDS_IMPORT_BATCH DROP CONSTRAINT CK_GDS_IMPORT_STREAM;
ALTER TABLE DMSMGR.TQP_GDS_IMPORT_BATCH ADD CONSTRAINT CK_GDS_IMPORT_STREAM CHECK (STREAM_KIND IN ('LAYER','PLACED'));

-- 5) Map 헤더: 원본 Payload 버전 컬럼 제거
ALTER TABLE DMSMGR.TQP_GDS_MAP DROP CONSTRAINT CK_GDS_MAP_FMT;
ALTER TABLE DMSMGR.TQP_GDS_MAP DROP COLUMN SOURCE_PAYLOAD_VERSION;
ALTER TABLE DMSMGR.TQP_GDS_MAP ADD CONSTRAINT CK_GDS_MAP_FMT CHECK (ID_GENERATOR_VERSION > 0 AND POINTS_FORMAT_VERSION > 0);

-- 확인
SELECT COUNT(*) AS SOURCE_TABLE_LEFT FROM DBA_TABLES WHERE OWNER = 'DMSMGR' AND TABLE_NAME = 'TQP_GDS_SOURCE_EL';
SELECT TABLE_NAME, COLUMN_NAME FROM DBA_TAB_COLUMNS
 WHERE OWNER = 'DMSMGR' AND TABLE_NAME IN ('TQP_GDS_MAP', 'TQP_GDS_IMPORT_JOB') AND COLUMN_NAME LIKE '%SOURCE%';
