-- 2026-10-12: E-Test 파일명 규칙 정형화 + 파일 요약 컬럼
-- 설계: 문서/2026-10-07_ETest_결과파일_Parsing_DB설계.md 13절 (제안안대로 적용)
-- 파일명 규칙: [Customer]_[Device]_[Wafer Type]_[Wafer Rev]_[Test Type]_[Test Date]_[Lot]_[Lot-Wafer No]$Fab$
--   예: CAI_OMM_ATV_A0_TSVET_20260902141031_U9-HS2633_U9-HS2633-01$Silterra$
--   Test Type = 기존 TEST_PROGRAM, Test Date = 기존 TEST_TIME, Lot = 기존 LOT_ID 를 그대로 쓴다 (N4).
--   FILE_PREFIX 는 남기되 새 저장(PARSE_RULE_VER 2)부터 채우지 않는다 (N5).
-- 추가 요약: PASS / FAIL Die 수(DUT Flag 기준), 미측정 셀 수 (CompleteEtFile 이 READY 로 바꿀 때 기록),
--            PARSE_RULE_VER (1 = 뒤에서부터 분해, 2 = 8칸 규칙), VIEW_SIDE (E-Test = BACK, 2026-10-06 회의).
-- 기존 행은 FILE_NAME 에서 채우고 PARSE_RULE_VER = 1 로 둔다.
-- 적용: 2026-10-12 로컬 docker oracle19c DMSMGR. 고객 DB 적용 여부는 별도 확인.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET ECHO OFF FEEDBACK ON

ALTER TABLE DMSMGR.TQP_GDS_SRC_FILE ADD (
    CUSTOMER          VARCHAR2(30 CHAR),
    FILE_DEVICE       VARCHAR2(50 CHAR),
    WAFER_TYPE        VARCHAR2(30 CHAR),
    WAFER_REV         VARCHAR2(20 CHAR),
    LOT_WAFER_NO      VARCHAR2(60 CHAR),
    FAB_NAME          VARCHAR2(50 CHAR),
    PASS_DIE_COUNT    NUMBER(10),
    FAIL_DIE_COUNT    NUMBER(10),
    NOT_TESTED_COUNT  NUMBER(10),
    PARSE_RULE_VER    NUMBER(3) DEFAULT 1 NOT NULL,
    VIEW_SIDE         VARCHAR2(10) DEFAULT 'BACK' NOT NULL
        CONSTRAINT CK_GDS_SRC_FILE_SIDE CHECK (VIEW_SIDE IN ('FRONT', 'BACK'))
);

-- 기존 행: 파일명 8칸(확장자 / $Fab$ 제외)에서 채우고, 요약 건수는 하위 테이블에서 센다.
UPDATE DMSMGR.TQP_GDS_SRC_FILE F
   SET CUSTOMER     = REGEXP_SUBSTR(REGEXP_REPLACE(REGEXP_REPLACE(F.FILE_NAME, '\.[^.]*$', ''), '\$[^$]+\$$', ''), '[^_]+', 1, 1),
       FILE_DEVICE  = REGEXP_SUBSTR(REGEXP_REPLACE(REGEXP_REPLACE(F.FILE_NAME, '\.[^.]*$', ''), '\$[^$]+\$$', ''), '[^_]+', 1, 2),
       WAFER_TYPE   = REGEXP_SUBSTR(REGEXP_REPLACE(REGEXP_REPLACE(F.FILE_NAME, '\.[^.]*$', ''), '\$[^$]+\$$', ''), '[^_]+', 1, 3),
       WAFER_REV    = REGEXP_SUBSTR(REGEXP_REPLACE(REGEXP_REPLACE(F.FILE_NAME, '\.[^.]*$', ''), '\$[^$]+\$$', ''), '[^_]+', 1, 4),
       LOT_WAFER_NO = REGEXP_SUBSTR(REGEXP_REPLACE(REGEXP_REPLACE(F.FILE_NAME, '\.[^.]*$', ''), '\$[^$]+\$$', ''), '[^_]+', 1, 8),
       FAB_NAME     = REGEXP_SUBSTR(REGEXP_REPLACE(F.FILE_NAME, '\.[^.]*$', ''), '\$([^$]+)\$$', 1, 1, NULL, 1),
       PASS_DIE_COUNT   = (SELECT COUNT(*) FROM DMSMGR.TQP_GDS_ET_DIE D WHERE D.SRC_FILE_SEQ = F.SRC_FILE_SEQ AND D.PASS_FLAG = 'P'),
       FAIL_DIE_COUNT   = (SELECT COUNT(*) FROM DMSMGR.TQP_GDS_ET_DIE D WHERE D.SRC_FILE_SEQ = F.SRC_FILE_SEQ AND D.PASS_FLAG = 'F'),
       NOT_TESTED_COUNT = (SELECT COUNT(*) FROM DMSMGR.TQP_GDS_ET_VALUE V WHERE V.SRC_FILE_SEQ = F.SRC_FILE_SEQ AND V.VALUE_STATUS = 'N'),
       PARSE_RULE_VER = 1;

COMMIT;

COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.CUSTOMER IS '파일명 1칸 Customer (예: CAI)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.FILE_DEVICE IS '파일명 2칸 Device 원문 (예: OMM). DMS DEVICE_ID 와 별개';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.WAFER_TYPE IS '파일명 3칸 Wafer Type (예: ATV)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.WAFER_REV IS '파일명 4칸 Wafer Rev (예: A0)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.LOT_WAFER_NO IS '파일명 8칸 Lot-Wafer No 원문 (예: U9-HS2633-01)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.FAB_NAME IS '파일명 끝 $...$ 꼬리표 (예: Silterra, Wafer 제조 Fab 으로 추정)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.TEST_PROGRAM IS '파일명 5칸 Test Type (예: TSVET)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.TEST_TIME IS '파일명 6칸 Test Date (yyyyMMddHHmmss)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.FILE_PREFIX IS '(PARSE_RULE_VER 1 만) 파일명 앞부분 원문. 2 부터는 CUSTOMER ~ WAFER_REV 로 나눠 저장';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.PASS_DIE_COUNT IS 'DUT Flag Pass Die 수 (READY 확정 때 기록)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.FAIL_DIE_COUNT IS 'DUT Flag Fail Die 수 (READY 확정 때 기록)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.NOT_TESTED_COUNT IS '미측정(-) 셀 수 (READY 확정 때 기록)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.PARSE_RULE_VER IS '파일명 해석 규칙: 1 = 뒤에서부터 분해(2026-10-07), 2 = 8칸 규칙 + $Fab$ (2026-10-12)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.VIEW_SIDE IS '좌표 기준 면: E-Test = BACK (2026-10-06 데이터기준 협의)';

EXIT
