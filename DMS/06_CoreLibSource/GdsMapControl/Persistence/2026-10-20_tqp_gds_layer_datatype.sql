-- 2026-10-20: GDS Layer 를 KLayout 처럼 Layer 번호 + DataType 으로 구분한다. TEXT 는 DATATYPE 이 없어 TEXTTYPE 을 DataType 자리에 쓴다.
-- 예: U8 Layer 18 = 18/0(도형) / 18/3(핀 번호 Label) / 18/4(Net 이름 Label).
-- 설계: 문서/설계/02_GDS/2026-10-20_U8_GDS_로딩_원인분석_설계.md 9절
--
-- 처리 순서
--  1) TQP_GDS_LAYER PK 를 참조하는 FK 4개(배치 도형 / Chain 탐색 Layer / Chain 규칙 2개)와 PK 해제
--  2) DATA_TYPE 컬럼 추가(기본값 0: DataType 을 모르는 이전 서버 저장도 그대로 동작)
--  3) 배치 도형 TEXT 행의 DATA_TYPE = TEXT_TYPE
--  4) Layer 행: 배치 도형에 있는 (번호, DataType) 조합마다 만든다(색 / 이름은 같은 번호의 기존 행). 배치 도형이 다른 DataType 에만 있는 번호의 DataType 0 행은 지운다.
--  5) Chain 탐색 Layer 행: 같은 번호의 Layer 행(DataType) 마다 만들고, 없어진 DataType 0 행은 지운다(이전에는 번호 = 그 번호의 모든 DataType)
--  6) PK / 인덱스 / FK 를 DataType 을 포함해 다시 만든다
-- 적용 전 로컬 데이터(2026-10-20 확인): BOUNDARY / PATH 는 모두 DataType 0, TEXT 는 Layer 775 TEXTTYPE 237. Chain 규칙 0행.
-- 적용 순서: 서비스 중지 -> 이 스크립트 -> 서버 BSL / 쿼리 XML 배포 -> 서비스 시작 -> GdsMap EXE 배포.
--   이전 서버(DataType 없는 쿼리)는 이 스크립트 뒤에 Map 복사(COPY_LAYER 가 DataType 0 으로만 복사)와
--   Layer 목록(같은 번호가 여러 행)이 맞지 않으므로 서버와 함께 적용한다.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET ECHO OFF FEEDBACK ON

-- 1) FK / PK 해제
ALTER TABLE DMSMGR.TQP_GDS_PLACED_EL DROP CONSTRAINT FK_GDS_PLACED_LAYER;
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_LAYER DROP CONSTRAINT FK_GDS_CHAIN_LAYER_MAP;
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_RULE DROP CONSTRAINT FK_GDS_CHAIN_RULE_L1;
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_RULE DROP CONSTRAINT FK_GDS_CHAIN_RULE_L2;
ALTER TABLE DMSMGR.TQP_GDS_LAYER DROP CONSTRAINT PK_GDS_LAYER DROP INDEX;
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_LAYER DROP CONSTRAINT PK_GDS_CHAIN_LAYER DROP INDEX;
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_RULE DROP CONSTRAINT PK_GDS_CHAIN_RULE DROP INDEX;
DROP INDEX DMSMGR.IX_GDS_PLACED_LAYER;
DROP INDEX DMSMGR.IX_GDS_CHAIN_LAYER_LY;
DROP INDEX DMSMGR.IX_GDS_CHAIN_RULE_L1;
DROP INDEX DMSMGR.IX_GDS_CHAIN_RULE_L2;

-- 2) 컬럼 추가
ALTER TABLE DMSMGR.TQP_GDS_LAYER ADD (DATA_TYPE NUMBER(5) DEFAULT 0 NOT NULL);
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_LAYER ADD (DATA_TYPE NUMBER(5) DEFAULT 0 NOT NULL);
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_RULE ADD (FIRST_DATA_TYPE NUMBER(5) DEFAULT 0 NOT NULL, SECOND_DATA_TYPE NUMBER(5) DEFAULT 0 NOT NULL);
COMMENT ON COLUMN DMSMGR.TQP_GDS_LAYER.DATA_TYPE IS 'GDS DataType (TEXT 는 TEXTTYPE). Layer = LAYER_ID + DATA_TYPE (KLayout 과 같은 단위)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_CHAIN_LAYER.DATA_TYPE IS 'Chain 탐색 Layer 의 DataType (TQP_GDS_LAYER.DATA_TYPE)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_CHAIN_RULE.FIRST_DATA_TYPE IS '연결 규칙 첫 Layer 의 DataType';
COMMENT ON COLUMN DMSMGR.TQP_GDS_CHAIN_RULE.SECOND_DATA_TYPE IS '연결 규칙 둘째 Layer 의 DataType';
COMMENT ON COLUMN DMSMGR.TQP_GDS_PLACED_EL.DATA_TYPE IS 'GDS DataType. TEXT 는 TEXTTYPE (TQP_GDS_LAYER FK, 2026-10-20)';

-- 3) TEXT 의 DataType = TEXTTYPE
UPDATE DMSMGR.TQP_GDS_PLACED_EL
   SET DATA_TYPE = TEXT_TYPE
 WHERE ELEMENT_TYPE = 'TEXT' AND TEXT_TYPE IS NOT NULL AND DATA_TYPE <> TEXT_TYPE;

-- 4) Layer 행: 배치 도형에 있는 조합 추가 -> 쓰지 않는 DataType 0 행 정리
INSERT INTO DMSMGR.TQP_GDS_LAYER (FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE, COLOR_ARGB, DISPLAY_NAME)
SELECT P.FACTORY, P.DEVICE_ID, P.LAYER_ID, P.DATA_TYPE, L.COLOR_ARGB, L.DISPLAY_NAME
  FROM (SELECT DISTINCT FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE FROM DMSMGR.TQP_GDS_PLACED_EL WHERE DATA_TYPE <> 0) P
  JOIN DMSMGR.TQP_GDS_LAYER L
    ON L.FACTORY = P.FACTORY AND L.DEVICE_ID = P.DEVICE_ID AND L.LAYER_ID = P.LAYER_ID AND L.DATA_TYPE = 0;

-- 5) Chain 탐색 Layer: 같은 번호의 다른 DataType Layer 행마다 추가 (4 의 DataType 0 정리보다 먼저)
INSERT INTO DMSMGR.TQP_GDS_CHAIN_LAYER (FACTORY, DEVICE_ID, CHAIN_SEQ, VERSION_NO, LAYER_ID, DATA_TYPE)
SELECT C.FACTORY, C.DEVICE_ID, C.CHAIN_SEQ, C.VERSION_NO, C.LAYER_ID, L.DATA_TYPE
  FROM DMSMGR.TQP_GDS_CHAIN_LAYER C
  JOIN DMSMGR.TQP_GDS_LAYER L
    ON L.FACTORY = C.FACTORY AND L.DEVICE_ID = C.DEVICE_ID AND L.LAYER_ID = C.LAYER_ID AND L.DATA_TYPE <> 0
 WHERE C.DATA_TYPE = 0;

-- 배치 도형이 그 번호의 다른 DataType 에만 있는 경우(예 775 -> 775/237) DataType 0 행은 쓰지 않는다
DELETE FROM DMSMGR.TQP_GDS_CHAIN_LAYER C
 WHERE C.DATA_TYPE = 0
   AND NOT EXISTS (SELECT 1 FROM DMSMGR.TQP_GDS_PLACED_EL P
                    WHERE P.FACTORY = C.FACTORY AND P.DEVICE_ID = C.DEVICE_ID AND P.LAYER_ID = C.LAYER_ID AND P.DATA_TYPE = 0)
   AND EXISTS (SELECT 1 FROM DMSMGR.TQP_GDS_LAYER L
                WHERE L.FACTORY = C.FACTORY AND L.DEVICE_ID = C.DEVICE_ID AND L.LAYER_ID = C.LAYER_ID AND L.DATA_TYPE <> 0);
DELETE FROM DMSMGR.TQP_GDS_LAYER L
 WHERE L.DATA_TYPE = 0
   AND NOT EXISTS (SELECT 1 FROM DMSMGR.TQP_GDS_PLACED_EL P
                    WHERE P.FACTORY = L.FACTORY AND P.DEVICE_ID = L.DEVICE_ID AND P.LAYER_ID = L.LAYER_ID AND P.DATA_TYPE = 0)
   AND EXISTS (SELECT 1 FROM DMSMGR.TQP_GDS_LAYER O
                WHERE O.FACTORY = L.FACTORY AND O.DEVICE_ID = L.DEVICE_ID AND O.LAYER_ID = L.LAYER_ID AND O.DATA_TYPE <> 0);

-- 6) PK / 인덱스 / FK 재생성
ALTER TABLE DMSMGR.TQP_GDS_LAYER ADD CONSTRAINT PK_GDS_LAYER PRIMARY KEY (FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE);
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_LAYER ADD CONSTRAINT PK_GDS_CHAIN_LAYER PRIMARY KEY (FACTORY, DEVICE_ID, CHAIN_SEQ, VERSION_NO, LAYER_ID, DATA_TYPE);
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_RULE ADD CONSTRAINT PK_GDS_CHAIN_RULE
    PRIMARY KEY (FACTORY, DEVICE_ID, CHAIN_SEQ, VERSION_NO, FIRST_LAYER_ID, FIRST_DATA_TYPE, SECOND_LAYER_ID, SECOND_DATA_TYPE);
CREATE INDEX DMSMGR.IX_GDS_PLACED_LAYER ON DMSMGR.TQP_GDS_PLACED_EL (FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE, PLACED_ELEMENT_ID);
CREATE INDEX DMSMGR.IX_GDS_CHAIN_LAYER_LY ON DMSMGR.TQP_GDS_CHAIN_LAYER (FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE);
CREATE INDEX DMSMGR.IX_GDS_CHAIN_RULE_L1 ON DMSMGR.TQP_GDS_CHAIN_RULE (FACTORY, DEVICE_ID, FIRST_LAYER_ID, FIRST_DATA_TYPE);
CREATE INDEX DMSMGR.IX_GDS_CHAIN_RULE_L2 ON DMSMGR.TQP_GDS_CHAIN_RULE (FACTORY, DEVICE_ID, SECOND_LAYER_ID, SECOND_DATA_TYPE);
ALTER TABLE DMSMGR.TQP_GDS_PLACED_EL ADD CONSTRAINT FK_GDS_PLACED_LAYER FOREIGN KEY (FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE)
    REFERENCES DMSMGR.TQP_GDS_LAYER (FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE);
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_LAYER ADD CONSTRAINT FK_GDS_CHAIN_LAYER_MAP FOREIGN KEY (FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE)
    REFERENCES DMSMGR.TQP_GDS_LAYER (FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE);
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_RULE ADD CONSTRAINT FK_GDS_CHAIN_RULE_L1 FOREIGN KEY (FACTORY, DEVICE_ID, FIRST_LAYER_ID, FIRST_DATA_TYPE)
    REFERENCES DMSMGR.TQP_GDS_LAYER (FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE);
ALTER TABLE DMSMGR.TQP_GDS_CHAIN_RULE ADD CONSTRAINT FK_GDS_CHAIN_RULE_L2 FOREIGN KEY (FACTORY, DEVICE_ID, SECOND_LAYER_ID, SECOND_DATA_TYPE)
    REFERENCES DMSMGR.TQP_GDS_LAYER (FACTORY, DEVICE_ID, LAYER_ID, DATA_TYPE);

COMMIT;
EXIT
