-- 2026-10-14: E-Test Para Setup 1단계 (Parameter 등록 / 대표 Chain / GDS Chain 연결)
-- 설계: 문서/2026-10-14_ETest_Para_Setup_설계.md 4절 / 4.7절 / 5.1절
--
-- 내용 (추가만 한다. 지금 배포된 업로드 / Limit 화면은 그대로 동작해야 한다)
--  1) TQP_GDS_ET_ITEM 을 Parameter 마스터로 쓰기 위한 컬럼 추가. 등록 Parameter = TEST_PROGRAM 이 있는 행.
--     예전 업로드가 만든 행(TEST_PROGRAM NULL, ITEM_NAME = 헤더 원문)은 그대로 둔다.
--     등록 행의 이름은 DB / 소스에서 그대로 쓸 수 있는 이름(대문자 / 숫자 / '_', 영문자로 시작)만 받는다.
--  2) UNIQUE (FACTORY, DEVICE_ID, ITEM_NAME) -> (FACTORY, DEVICE_ID, TEST_PROGRAM, ITEM_NAME). 같은 헤더를 공정마다 따로 등록한다.
--  3) TQP_GDS_ET_REP_CHAIN: 단자(E-Test Chain) 이름 -> 대표 Chain 이름 (사용자 입력). GDS 대표 Device 단위.
--  4) TQP_GDS_ET_CHAIN_LINK: 대표 Chain -> GDS Setup Chain (1:1). GDS Chain 을 지우면 연결도 지워진다(CASCADE).
--
-- 2단계(별도 DDL, Limit 화면 정리 / Upload 재설계 구현 때): 로컬 E-Test 데이터 정리 -> TEST_PROGRAM NOT NULL ->
--   TQP_GDS_ET_LIMIT FK -> TQP_GDS_ET_CHAIN_GROUP DROP.
-- 적용: 로컬 docker oracle19c-DMS DMSMGR. 고객 DB 적용 여부는 별도 확인.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET ECHO OFF FEEDBACK ON

-- 1) Parameter 마스터 컬럼
ALTER TABLE DMSMGR.TQP_GDS_ET_ITEM ADD (
        TEST_PROGRAM     VARCHAR2(50 CHAR),
        HEADER_TEXT      VARCHAR2(200 CHAR),
        MEAS_TYPE        VARCHAR2(30 CHAR),
        CHAIN_TYPE       VARCHAR2(30 CHAR),
        FORCE_LEG        VARCHAR2(4 CHAR),
        FORCE_LEG2       VARCHAR2(4 CHAR),
        USE_FLAG         CHAR(1) DEFAULT 'Y' NOT NULL,
        REG_SOURCE       VARCHAR2(10 CHAR),
        REG_FILE_NAME    VARCHAR2(260 CHAR),
        REMARK           VARCHAR2(200 CHAR)
   );

ALTER TABLE DMSMGR.TQP_GDS_ET_ITEM ADD (
        CONSTRAINT CK_GDS_ET_ITEM_USE CHECK (USE_FLAG IN ('Y', 'N')),
        CONSTRAINT CK_GDS_ET_ITEM_SOURCE CHECK (REG_SOURCE IS NULL OR REG_SOURCE IN ('FILE', 'SPEC')),
        CONSTRAINT CK_GDS_ET_ITEM_LEG CHECK ((FORCE_LEG IS NULL OR FORCE_LEG IN ('FH', 'FL')) AND (FORCE_LEG2 IS NULL OR FORCE_LEG2 IN ('FH', 'FL'))),
        CONSTRAINT CK_GDS_ET_ITEM_PARA CHECK (TEST_PROGRAM IS NULL OR (
                REGEXP_LIKE(TEST_PROGRAM, '^[A-Z][A-Z0-9_]*$')
            AND REGEXP_LIKE(ITEM_NAME, '^[A-Z][A-Z0-9_]*$') AND LENGTH(ITEM_NAME) <= 50
            AND REGEXP_LIKE(CHAIN_NAME, '^[A-Z][A-Z0-9_]*$')
            AND (CHAIN_NAME2 IS NULL OR REGEXP_LIKE(CHAIN_NAME2, '^[A-Z][A-Z0-9_]*$'))
            AND HEADER_TEXT IS NOT NULL AND REG_SOURCE IS NOT NULL))
   );

-- 2) UNIQUE 교체 (같은 헤더를 공정마다 따로 등록). 예전 행은 TEST_PROGRAM NULL 이고 ITEM_NAME 이 Device 안에서 이미 유일하다.
ALTER TABLE DMSMGR.TQP_GDS_ET_ITEM DROP CONSTRAINT UQ_GDS_ET_ITEM_NAME DROP INDEX;
ALTER TABLE DMSMGR.TQP_GDS_ET_ITEM ADD CONSTRAINT UQ_GDS_ET_ITEM_PARA UNIQUE (FACTORY, DEVICE_ID, TEST_PROGRAM, ITEM_NAME);

-- 단자 2 로 Parameter 찾기 (단자 1 색인 IX_GDS_ET_ITEM_CHAIN 은 이미 있음)
CREATE INDEX DMSMGR.IX_GDS_ET_ITEM_CHAIN2 ON DMSMGR.TQP_GDS_ET_ITEM (FACTORY, DEVICE_ID, CHAIN_NAME2);

COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.TEST_PROGRAM IS '공정(Test Type: TSVET / COWET / FT). 값이 있으면 Para Setup 에서 등록한 Parameter, NULL 이면 예전 업로드가 만든 항목';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.HEADER_TEXT IS '등록 Parameter 의 헤더 원문 (공백 정리 / 끝 #번호 제거, 대소문자 유지). ITEM_NAME 은 DB / 소스용 변환 이름';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.MEAS_TYPE IS 'Measurement type (RESISTANCE / CONNECTIVITY / CONTINUITY / LEAKAGE)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.CHAIN_TYPE IS '단자 1 의 Chain type (TSVDC / C4DC / PIC_SERP ...)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.FORCE_LEG IS '단자 1 끝 Force leg (FH / FL)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.FORCE_LEG2 IS '단자 2 끝 Force leg (FH / FL)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.USE_FLAG IS 'Y / N. N 이면 다음 업로드부터 값을 저장 / 판정하지 않는다 (저장된 값은 보관)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.REG_SOURCE IS '등록 출처 FILE(결과 파일) / SPEC(고객 Spec 표)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.REG_FILE_NAME IS '등록에 쓴 파일 이름';

-- 3) 대표 Chain (단자 -> 대표 Chain 이름)
CREATE TABLE DMSMGR.TQP_GDS_ET_REP_CHAIN
   (    FACTORY          VARCHAR2(30 CHAR) NOT NULL,
        DEVICE_ID        VARCHAR2(50 CHAR) NOT NULL,
        TERMINAL_NAME    VARCHAR2(64 CHAR) NOT NULL,
        REP_CHAIN_NAME   VARCHAR2(64 CHAR) NOT NULL,
        REMARK           VARCHAR2(200 CHAR),
        CREATE_USER      VARCHAR2(30),
        CREATE_TIME      DATE DEFAULT SYSDATE NOT NULL,
        UPDATE_USER      VARCHAR2(30),
        UPDATE_TIME      DATE,
        CONSTRAINT CK_GDS_ET_REP_CHAIN_NAME CHECK (REGEXP_LIKE(TERMINAL_NAME, '^[A-Z][A-Z0-9_]*$') AND REGEXP_LIKE(REP_CHAIN_NAME, '^[A-Z][A-Z0-9_]*$')),
        CONSTRAINT PK_GDS_ET_REP_CHAIN PRIMARY KEY (FACTORY, DEVICE_ID, TERMINAL_NAME)
   );

CREATE INDEX DMSMGR.IX_GDS_ET_REP_CHAIN_REP ON DMSMGR.TQP_GDS_ET_REP_CHAIN (FACTORY, DEVICE_ID, REP_CHAIN_NAME);

COMMENT ON TABLE DMSMGR.TQP_GDS_ET_REP_CHAIN IS 'E-Test 단자(Chain) 이름 -> 대표 Chain. 같은 REP_CHAIN_NAME 끼리 한 물리 Chain. 사용자가 이름을 입력해 묶는다';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_REP_CHAIN.DEVICE_ID IS 'GDS 대표 Device (예 U9). E-Test Device 는 TQP_GDS_MAP_SUB_DEVICE 로 연결';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_REP_CHAIN.TERMINAL_NAME IS '단자 이름 = 헤더 @ 뒤 / : 뒤 Chain 이름 (변환 이름, Force leg 포함)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_REP_CHAIN.REP_CHAIN_NAME IS '대표 Chain 이름 (사용자 입력을 변환한 이름)';

-- 4) 대표 Chain -> GDS Setup Chain (1:1)
CREATE TABLE DMSMGR.TQP_GDS_ET_CHAIN_LINK
   (    FACTORY          VARCHAR2(30 CHAR) NOT NULL,
        DEVICE_ID        VARCHAR2(50 CHAR) NOT NULL,
        REP_CHAIN_NAME   VARCHAR2(64 CHAR) NOT NULL,
        CHAIN_SEQ        NUMBER NOT NULL,
        GDS_CHAIN_NAME   VARCHAR2(200 CHAR),
        LINK_TYPE        VARCHAR2(10 CHAR) NOT NULL,
        REMARK           VARCHAR2(200 CHAR),
        CREATE_USER      VARCHAR2(30),
        CREATE_TIME      DATE DEFAULT SYSDATE NOT NULL,
        UPDATE_USER      VARCHAR2(30),
        UPDATE_TIME      DATE,
        CONSTRAINT CK_GDS_ET_CHAIN_LINK_TYPE CHECK (LINK_TYPE IN ('NAME', 'MANUAL')),
        CONSTRAINT CK_GDS_ET_CHAIN_LINK_REP CHECK (REGEXP_LIKE(REP_CHAIN_NAME, '^[A-Z][A-Z0-9_]*$')),
        CONSTRAINT PK_GDS_ET_CHAIN_LINK PRIMARY KEY (FACTORY, DEVICE_ID, REP_CHAIN_NAME),
        CONSTRAINT UQ_GDS_ET_CHAIN_LINK_SEQ UNIQUE (FACTORY, DEVICE_ID, CHAIN_SEQ),
        CONSTRAINT FK_GDS_ET_CHAIN_LINK_CHAIN FOREIGN KEY (FACTORY, DEVICE_ID, CHAIN_SEQ)
            REFERENCES DMSMGR.TQP_GDS_CHAIN (FACTORY, DEVICE_ID, CHAIN_SEQ) ON DELETE CASCADE
   );

COMMENT ON TABLE DMSMGR.TQP_GDS_ET_CHAIN_LINK IS 'E-Test 대표 Chain -> GDS Setup Chain (1:1). GDS Chain 삭제 시 연결만 삭제(CASCADE)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_CHAIN_LINK.GDS_CHAIN_NAME IS '연결할 때의 GDS Chain 이름 (이름이 바뀐 것을 알아내는 용도)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_CHAIN_LINK.LINK_TYPE IS 'NAME = GDS 이름이 대표 이름 또는 구성 단자와 같아 연결 / MANUAL = 사용자가 고름';

EXIT
