-- U8 GDS 원점 이동 되돌리기 (2026-10-22)
-- 2026-10-22_u8_gds_origin_center.sql 이 만든 백업(TQP_GDS_PLACED_EL_U8BAK / TQP_GDS_CHAIN_MEMBER_U8BAK)으로 원래 좌표를 돌려놓는다.
-- 백업 테이블은 지우지 않는다(확인 뒤 직접 DROP). 끝나면 SEMDMS Service / DACrux 를 다시 시작한다.

WHENEVER SQLERROR EXIT ROLLBACK
SET SERVEROUTPUT ON
SET FEEDBACK OFF

MERGE INTO TQP_GDS_PLACED_EL N
USING TQP_GDS_PLACED_EL_U8BAK B
   ON (N.FACTORY = B.FACTORY AND N.DEVICE_ID = B.DEVICE_ID AND N.PLACED_ELEMENT_ID = B.PLACED_ELEMENT_ID)
 WHEN MATCHED THEN UPDATE SET N.MIN_X = B.MIN_X, N.MIN_Y = B.MIN_Y, N.MAX_X = B.MAX_X, N.MAX_Y = B.MAX_Y, N.POINTS_BIN = B.POINTS_BIN;

MERGE INTO TQP_GDS_CHAIN_MEMBER N
USING TQP_GDS_CHAIN_MEMBER_U8BAK B
   ON (N.FACTORY = B.FACTORY AND N.DEVICE_ID = B.DEVICE_ID AND N.CHAIN_SEQ = B.CHAIN_SEQ AND N.VERSION_NO = B.VERSION_NO
       AND N.PLACED_ELEMENT_ID = B.PLACED_ELEMENT_ID)
 WHEN MATCHED THEN UPDATE SET N.MARKER_X = B.MARKER_X, N.MARKER_Y = B.MARKER_Y;

COMMIT;
PROMPT U8 GDS 좌표를 백업으로 되돌렸습니다. SEMDMS Service / DACrux 를 다시 시작하세요.
