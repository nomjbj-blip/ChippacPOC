-- 2026-10-07: E-Test 결과 파일 기준 정보 테이블 TQP_GDS_SRC_FILE
-- 설계: 문서/2026-10-07_ETest_결과파일_Parsing_DB설계.md 9절
-- 범위: E-Test 결과 파일만 (KLARF 는 별도 작업). 측정값 / Die / Limit 은 나중 설계.
-- 한 행 = E-Test 파일 1개. 기준 정보는 파일명에서 읽은 값을 그대로 넣는다.
-- WAFER_ID 는 LOT_ID + '-' + 2자리 SLOT_NO 가상 컬럼이다 (R1). INSERT / UPDATE 문에 넣지 않는다 (ORA-54013).
-- 적용: 미적용 (로컬 docker oracle19c DMSMGR 적용은 승인 후). 고객 DB 적용 여부는 별도 확인.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET ECHO OFF FEEDBACK ON

CREATE SEQUENCE DMSMGR.SRC_FILE_SEQ START WITH 1 INCREMENT BY 1 MINVALUE 1 NOCYCLE CACHE 20;

CREATE TABLE DMSMGR.TQP_GDS_SRC_FILE
   (    SRC_FILE_SEQ     NUMBER NOT NULL,
        FILE_NAME        VARCHAR2(260 CHAR) NOT NULL,
        FACTORY          VARCHAR2(30 CHAR) NOT NULL,
        DEVICE_ID        VARCHAR2(50 CHAR) NOT NULL,
        LOT_ID           VARCHAR2(50 CHAR) NOT NULL,
        SLOT_NO          NUMBER(3) NOT NULL,
        WAFER_ID         VARCHAR2(60 CHAR) GENERATED ALWAYS AS (
                             LOT_ID || '-' || LPAD(TO_CHAR(SLOT_NO), 2, '0')) VIRTUAL,
        TEST_PROGRAM     VARCHAR2(50 CHAR) NOT NULL,
        TEST_TIME        DATE NOT NULL,
        FILE_PREFIX      VARCHAR2(100 CHAR),
        CREATE_USER      VARCHAR2(30),
        CREATE_TIME      DATE DEFAULT SYSDATE NOT NULL,
        UPDATE_USER      VARCHAR2(30),
        UPDATE_TIME      DATE,
        CONSTRAINT CK_GDS_SRC_FILE_SLOT CHECK (SLOT_NO BETWEEN 1 AND 99),
        CONSTRAINT PK_GDS_SRC_FILE PRIMARY KEY (SRC_FILE_SEQ),
        CONSTRAINT UQ_GDS_SRC_FILE_TEST UNIQUE (FACTORY, DEVICE_ID, LOT_ID, SLOT_NO, TEST_PROGRAM, TEST_TIME)
   );

CREATE INDEX DMSMGR.IX_GDS_SRC_FILE_WAFER ON DMSMGR.TQP_GDS_SRC_FILE (FACTORY, DEVICE_ID, WAFER_ID);

COMMENT ON TABLE DMSMGR.TQP_GDS_SRC_FILE IS 'E-Test 결과 파일 기준 정보. 한 행 = 파일 1개';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.FILE_NAME IS '원본 파일명';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.DEVICE_ID IS 'TQP_GDS_MAP.DEVICE_ID 와 같은 값 체계 (업로드 화면에서 선택)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.LOT_ID IS '파일명 Lot (예: RH-HS2615)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.SLOT_NO IS '파일명 Wafer 끝 숫자 (RH-HS2615-02 -> 2)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.WAFER_ID IS 'LOT_ID || ''-'' || 2자리 SLOT_NO (가상 컬럼)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.TEST_PROGRAM IS '파일명 시험 프로그램 (예: TSVET)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.TEST_TIME IS '파일명 14자리 시험 일시';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.FILE_PREFIX IS '파일명 앞부분 원문 (예: CAI_OMM_ATV_A0, 의미 확인 필요)';

EXIT
