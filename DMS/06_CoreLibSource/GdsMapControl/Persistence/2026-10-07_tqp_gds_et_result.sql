-- 2026-10-07: E-Test 결과 Data 테이블 (측정 항목 / Die / 측정값) + 파일 헤더 보강
-- 설계: 문서/2026-10-07_ETest_결과파일_Parsing_DB설계.md 10절
-- 선행: 2026-10-07_tqp_gds_src_file.sql (TQP_GDS_SRC_FILE) 적용 완료 상태여야 한다.
-- 범위: E-Test 결과만. Limit (판정 기준) 은 Limit 설정 화면과 함께 나중에 설계한다.
-- 적용: 미적용 (로컬 docker oracle19c DMSMGR 적용은 승인 후). 고객 DB 적용 여부는 별도 확인.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET ECHO OFF FEEDBACK ON

-- 1. 파일 헤더 보강: 저장 건수 검증 / 적재 상태 (Bulk 저장 중 실패한 파일을 READY 로 보이지 않게)
ALTER TABLE DMSMGR.TQP_GDS_SRC_FILE ADD (
    SHEET_NAME     VARCHAR2(50 CHAR),
    DIE_COUNT      NUMBER(10),
    ITEM_COUNT     NUMBER(10),
    VALUE_COUNT    NUMBER(10),
    LOAD_STATUS    VARCHAR2(20) DEFAULT 'LOADING' NOT NULL
        CONSTRAINT CK_GDS_SRC_FILE_STATUS CHECK (LOAD_STATUS IN ('LOADING', 'READY'))
);

-- 2. 측정 항목 마스터 (Device 단위, 파일마다 재사용)
--    헤더 형식: {PARA_NAME}[={COND_VALUE}]@{CHAIN_NAME}[:{CHAIN_NAME2}]
--    예: Continuity_iforce=8.0mA@C4DC_210_3_FH -> PARA_NAME Continuity_iforce / COND_VALUE 8.0mA / CHAIN_NAME C4DC_210_3_FH
CREATE SEQUENCE DMSMGR.ET_ITEM_SEQ START WITH 1 INCREMENT BY 1 MINVALUE 1 NOCYCLE CACHE 20;

CREATE TABLE DMSMGR.TQP_GDS_ET_ITEM
   (    ET_ITEM_SEQ      NUMBER NOT NULL,
        FACTORY          VARCHAR2(30 CHAR) NOT NULL,
        DEVICE_ID        VARCHAR2(50 CHAR) NOT NULL,
        ITEM_NAME        VARCHAR2(200 CHAR) NOT NULL,
        PARA_NAME        VARCHAR2(50 CHAR) NOT NULL,
        COND_VALUE       VARCHAR2(20 CHAR),
        CHAIN_NAME       VARCHAR2(64 CHAR) NOT NULL,
        CHAIN_NAME2      VARCHAR2(64 CHAR),
        UNIT             VARCHAR2(10 CHAR),
        TEST_NO          NUMBER(10),
        DISPLAY_ORDER    NUMBER(10),
        CREATE_USER      VARCHAR2(30),
        CREATE_TIME      DATE DEFAULT SYSDATE NOT NULL,
        UPDATE_USER      VARCHAR2(30),
        UPDATE_TIME      DATE,
        CONSTRAINT PK_GDS_ET_ITEM PRIMARY KEY (ET_ITEM_SEQ),
        CONSTRAINT UQ_GDS_ET_ITEM_NAME UNIQUE (FACTORY, DEVICE_ID, ITEM_NAME)
   );

CREATE INDEX DMSMGR.IX_GDS_ET_ITEM_CHAIN ON DMSMGR.TQP_GDS_ET_ITEM (FACTORY, DEVICE_ID, CHAIN_NAME);
CREATE INDEX DMSMGR.IX_GDS_ET_ITEM_PARA ON DMSMGR.TQP_GDS_ET_ITEM (FACTORY, DEVICE_ID, PARA_NAME, COND_VALUE);

-- 3. Die 정보 (파일 1개의 Die 행)
CREATE TABLE DMSMGR.TQP_GDS_ET_DIE
   (    SRC_FILE_SEQ     NUMBER NOT NULL,
        DUT_NO           NUMBER(10) NOT NULL,
        DIE_X            NUMBER(10) NOT NULL,
        DIE_Y            NUMBER(10) NOT NULL,
        HW_BIN           NUMBER(10),
        SW_BIN           NUMBER(10),
        PASS_FLAG        CHAR(1) NOT NULL,
        FLAG_CODE        VARCHAR2(10),
        TEST_TIME_MS     NUMBER(10),
        TESTS_EXECUTED   NUMBER(10),
        HEAD_SITE        VARCHAR2(30 CHAR),
        CONSTRAINT CK_GDS_ET_DIE_PASS CHECK (PASS_FLAG IN ('P', 'F')),
        CONSTRAINT PK_GDS_ET_DIE PRIMARY KEY (SRC_FILE_SEQ, DUT_NO),
        CONSTRAINT UQ_GDS_ET_DIE_XY UNIQUE (SRC_FILE_SEQ, DIE_X, DIE_Y),
        CONSTRAINT FK_GDS_ET_DIE_FILE FOREIGN KEY (SRC_FILE_SEQ)
            REFERENCES DMSMGR.TQP_GDS_SRC_FILE (SRC_FILE_SEQ) ON DELETE CASCADE
   );

-- 4. 측정값 (Die x 항목 1행, 세로형)
CREATE TABLE DMSMGR.TQP_GDS_ET_VALUE
   (    SRC_FILE_SEQ     NUMBER NOT NULL,
        DUT_NO           NUMBER(10) NOT NULL,
        ET_ITEM_SEQ      NUMBER NOT NULL,
        MEAS_VALUE       BINARY_DOUBLE,
        VALUE_STATUS     CHAR(1) NOT NULL,
        CONSTRAINT CK_GDS_ET_VALUE_STATUS CHECK (VALUE_STATUS IN ('V', 'N', 'E')),
        CONSTRAINT CK_GDS_ET_VALUE_NULL CHECK ((VALUE_STATUS = 'V' AND MEAS_VALUE IS NOT NULL)
                                            OR (VALUE_STATUS IN ('N', 'E') AND MEAS_VALUE IS NULL)),
        CONSTRAINT PK_GDS_ET_VALUE PRIMARY KEY (SRC_FILE_SEQ, DUT_NO, ET_ITEM_SEQ),
        CONSTRAINT FK_GDS_ET_VALUE_DIE FOREIGN KEY (SRC_FILE_SEQ, DUT_NO)
            REFERENCES DMSMGR.TQP_GDS_ET_DIE (SRC_FILE_SEQ, DUT_NO) ON DELETE CASCADE,
        CONSTRAINT FK_GDS_ET_VALUE_ITEM FOREIGN KEY (ET_ITEM_SEQ)
            REFERENCES DMSMGR.TQP_GDS_ET_ITEM (ET_ITEM_SEQ)
   );

CREATE INDEX DMSMGR.IX_GDS_ET_VALUE_ITEM ON DMSMGR.TQP_GDS_ET_VALUE (SRC_FILE_SEQ, ET_ITEM_SEQ);
CREATE INDEX DMSMGR.IX_GDS_ET_VALUE_ITEMONLY ON DMSMGR.TQP_GDS_ET_VALUE (ET_ITEM_SEQ);

COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.LOAD_STATUS IS 'LOADING = 저장 중 / READY = 건수 검증 완료';
COMMENT ON COLUMN DMSMGR.TQP_GDS_SRC_FILE.VALUE_COUNT IS '저장된 측정값 행 수 (= DIE_COUNT x ITEM_COUNT 이어야 READY)';
COMMENT ON TABLE DMSMGR.TQP_GDS_ET_ITEM IS 'E-Test 측정 항목 마스터 (Device 단위)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.ITEM_NAME IS '원문 헤더 (예: Continuity_iforce=8.0mA@C4DC_210_3_FH)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.PARA_NAME IS 'Para 이름 (= 앞 부분, 예: Continuity_iforce / Leakage_Parallel)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.COND_VALUE IS '= 뒤 조건 값 (예: 8.0mA), 없으면 NULL';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.CHAIN_NAME IS '@ 뒤 Chain 이름 (예: C4DC_210_3_FH)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_ITEM.CHAIN_NAME2 IS 'Leakage_Serial 등 A:B 형식의 두 번째 Chain';
COMMENT ON TABLE DMSMGR.TQP_GDS_ET_DIE IS 'E-Test Die 정보 (파일 행 단위, 좌표는 파일 원본 그대로)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_DIE.DUT_NO IS 'A열 #3 -> 3';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_DIE.PASS_FLAG IS 'DUT Flag Pass -> P / Failed -> F';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_DIE.FLAG_CODE IS 'DUT Flag 코드 (예: 0x08)';
COMMENT ON TABLE DMSMGR.TQP_GDS_ET_VALUE IS 'E-Test 측정값 (Die x 항목)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_VALUE.VALUE_STATUS IS 'V = 숫자 / N = 미측정(-) / E = 빈 값';

EXIT
