-- 2026-10-07: E-Test Para Limit 테이블 TQP_GDS_ET_LIMIT
-- 설계: 문서/설계/04_ETest/2026-10-07_ETest_Limit_설정_설계.md 10절 (결정)
--   "para 별로 사용자가 구간 선택 / device 별로 설정 / 대소문자가 다를 수 있어 등록 시 Upper / enable 기능 / Limit 는 한쪽만 있을 수 있다"
-- 키: FACTORY + DEVICE_ID + PARA_NAME (대문자). 조건(iforce) / Chain 구분 없음.
-- 판정: ENABLE_FLAG = 'Y' 이고 값이 LOWER_LIMIT 미만 또는 UPPER_LIMIT 초과면 Fail (경계값 Pass). 한쪽이 NULL 이면 그쪽은 검사 안 함.
-- 적용: 2026-10-07 로컬 docker oracle19c DMSMGR. 고객 DB 적용 여부는 별도 확인.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET ECHO OFF FEEDBACK ON

CREATE TABLE DMSMGR.TQP_GDS_ET_LIMIT
   (    FACTORY          VARCHAR2(30 CHAR) NOT NULL,
        DEVICE_ID        VARCHAR2(50 CHAR) NOT NULL,
        PARA_NAME        VARCHAR2(50 CHAR) NOT NULL,
        LOWER_LIMIT      BINARY_DOUBLE,
        UPPER_LIMIT      BINARY_DOUBLE,
        UNIT             VARCHAR2(10 CHAR),
        ENABLE_FLAG      CHAR(1) DEFAULT 'Y' NOT NULL,
        REMARK           VARCHAR2(200 CHAR),
        CREATE_USER      VARCHAR2(30),
        CREATE_TIME      DATE DEFAULT SYSDATE NOT NULL,
        UPDATE_USER      VARCHAR2(30),
        UPDATE_TIME      DATE,
        CONSTRAINT CK_GDS_ET_LIMIT_ONE CHECK (LOWER_LIMIT IS NOT NULL OR UPPER_LIMIT IS NOT NULL),
        CONSTRAINT CK_GDS_ET_LIMIT_RANGE CHECK (LOWER_LIMIT IS NULL OR UPPER_LIMIT IS NULL OR LOWER_LIMIT <= UPPER_LIMIT),
        CONSTRAINT CK_GDS_ET_LIMIT_ENABLE CHECK (ENABLE_FLAG IN ('Y', 'N')),
        CONSTRAINT CK_GDS_ET_LIMIT_UPPER CHECK (PARA_NAME = UPPER(PARA_NAME)),
        CONSTRAINT PK_GDS_ET_LIMIT PRIMARY KEY (FACTORY, DEVICE_ID, PARA_NAME)
   );

COMMENT ON TABLE DMSMGR.TQP_GDS_ET_LIMIT IS 'E-Test Para Limit (Device 단위, Para 대문자)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_LIMIT.PARA_NAME IS 'Para 이름 대문자 (측정 항목 PARA_NAME 과 UPPER 로 비교)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_LIMIT.LOWER_LIMIT IS '하한, NULL = 하한 없음 (값 < 하한 이면 Fail)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_LIMIT.UPPER_LIMIT IS '상한, NULL = 상한 없음 (값 > 상한 이면 Fail)';
COMMENT ON COLUMN DMSMGR.TQP_GDS_ET_LIMIT.ENABLE_FLAG IS 'Y = 판정에 사용 / N = 값만 보관';

EXIT
